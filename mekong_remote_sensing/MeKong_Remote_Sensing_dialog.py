    def slic_shapefile(self, dst): #dst
        path_raster = self.comboBox.currentText()
        raster_layer = QgsProject.instance().mapLayersByName(path_raster)[0]
        raster_path = raster_layer.source()
        out_shapefile = self.out_path2
        thamso3 = self.handlePage3Values()
        lines = thamso3.split('\n')
        parameters = {}
        for line in lines:
            if line.startswith('n_segment:'):
                n_segment_value = line.split(':')[1].strip()
                parameters['n_segment'] = int(n_segment_value)
            elif line.startswith('compactness:'):
                compactness_value = line.split(':')[1].strip()
                parameters['compactness'] = int(compactness_value)
            elif line.startswith('sigma:'):
                sigma_value = line.split(':')[1].strip()
                parameters['sigma'] = int(sigma_value)
            elif line.startswith('max_iter:'):
                max_iter_value = line.split(':')[1].strip()
                parameters['max_iter'] = int(max_iter_value)

        n_segments = parameters['n_segment']
        compactness = parameters['compactness']
        sigma = parameters['sigma']
        max_num_iter = parameters['max_iter']

        dataset = rasterio.open(raster_path)
        n=3
        band=[]
        for i in range(dataset.count):
            band.append(dataset.read(i+1))
        affine = dataset.transform
        img = np.column_stack([dataset.read(n-i).flatten() for i in range(n)])
        img = img.reshape(dataset.shape[0],dataset.shape[1],n)
        img=img_as_float(img)
        img/=255

        Slic = slic(img, n_segments=n_segments,compactness=compactness,sigma=sigma,max_num_iter=max_num_iter,convert2lab=True)
        labels = np.int32(Slic)
        self.luu_nhan(dst, labels, dataset)
        
        shapes = rasterio.features.shapes(labels, mask=None, connectivity=4, transform=dataset.transform)
        schema = {'geometry': 'Polygon'}
        properties = {}
        properties['Cluster_ID'] = 'int:64'
        for i in range(dataset.count):
            m = 'Mean'+str(i)
            m1 = 'Max'+str(i)
            m2 = 'Min'+str(i)
            s = 'Std' +str(i)
            properties[m] = 'float:32.15'
            properties[m1] = 'float:32.15'
            properties[m2] = 'float:32.15'
            properties[s] = 'float:32.15'
        properties['Class'] = 'str'
        schema['properties'] = properties

        c = fiona.open(out_shapefile, 'w', crs=dataset.crs, driver='ESRI Shapefile', schema=schema)
        j=0
        for shp, val in shapes:
            j+=1
            obj={}
