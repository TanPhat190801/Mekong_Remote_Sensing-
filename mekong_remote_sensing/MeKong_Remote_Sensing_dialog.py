    def kmeans_clustering(self):
        path_raster = self.comboBox.currentText()
        raster_layer = QgsProject.instance().mapLayersByName(path_raster)[0]
        raster_path = raster_layer.source()
        out_raster = self.out_path1
        thamso = self.handlePage1Values()
        lines = thamso.split('\n')
        parameters = {}
        for line in lines:
            if line.startswith('Cluster:'):
                cluster_value = line.split(':')[1].strip()
                parameters['Cluster'] = int(cluster_value)
            elif line.startswith('n_init:'):
                n_init_value = line.split(':')[1].strip()
                parameters['n_init'] = int(n_init_value)
            elif line.startswith('max_iter:'):
                max_iter_value = line.split(':')[1].strip()
                parameters['max_iter'] = int(max_iter_value)   

        n_clusters = parameters['Cluster']
        n_init = parameters['n_init']
        max_iter = parameters['max_iter']

        dataset = rasterio.open(raster_path)
        band=[]
        n=3
        for i in range(dataset.count):
            band.append(dataset.read(i+1))
        samples = np.column_stack([band[i].flatten() for i in range(n)])

        kmeans = KMeans(n_clusters=n_clusters, n_init=n_init, max_iter=max_iter)
        temp = kmeans.fit_predict(samples)
        labels = temp.reshape(dataset.shape)  

        with rasterio.open(
            out_raster,
            'w',
            driver = 'GTiff',
            height=labels.shape[0],
            width=labels.shape[1],
            count=1,
            dtype=labels.dtype,
            crs=dataset.crs,
            transform=dataset.transform,
        ) as dst:
            dst.write(labels, 1)

        raster_name = os.path.basename(out_raster)
        raster_out = QgsRasterLayer(out_raster, raster_name, "gdal")
        QgsProject.instance().addMapLayer(raster_out)
        #hiển thị thông báo
        QMessageBox.information(self, "Clustering Rasterfile Complete", "Clustering Rasterfile Successfully.")
        
