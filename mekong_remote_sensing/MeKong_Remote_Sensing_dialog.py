    def outputfile(self):
        file_dialog = QFileDialog()
        file_dialog.setAcceptMode(QFileDialog.AcceptSave)
        file_dialog.setNameFilter("Shapefile (*.shp*)")
        file_dialog.setDefaultSuffix(".shp")
        default_directory = "D:/MekongRemoteSensing/Classification"
        file_dialog.setDirectory(default_directory)
        if file_dialog.exec_():
            selected_directory = file_dialog.selectedFiles()
            if len(selected_directory) > 0:
                output_path = selected_directory[0]
                self.out_path = output_path
                self.comboBox.addItem(self.out_path)

    def show_selected_item(self, item):
        selected_items = [self.listwidget.item(i) for i in range (self.listwidget.count())]
        selected_text = [item.text() for item in selected_items if item.checkState() == Qt.Checked]
        self.showlineedit.setText(",".join(selected_text) if selected_text else "No Selected Column")

    def mergershapefile(self):
        outpath = self.comboBox.currentText()
        selected_items = [self.listwidget.item(i) for i in range (self.listwidget.count())]
        selected_text = [item.text() for item in selected_items if item.checkState() == Qt.Checked]
        if len (selected_text) < 2:
            QMessageBox.warning(self, "Warning", "Vui lòng chọn ít nhất 2 layer")
        elif not outpath:
            QMessageBox.warning(self, "Warning", "Vui lòng chọn Output")
        else:
            gdf_list = []
            for layer_name in selected_text:
                layer = QgsProject.instance().mapLayersByName(layer_name)[0]
                self.duong_dan_file = layer.dataProvider().dataSourceUri()
                gdf_list.append(gpd.read_file(self.duong_dan_file))
            merged_gdf = gpd.GeoDataFrame(pd.concat(gdf_list, ignore_index=True))
            merged_gdf.to_file(outpath)

            layer_file = os.path.basename(outpath)
            layer_out = QgsVectorLayer(outpath, layer_file, "ogr")
            QgsProject.instance().addMapLayer(layer_out)

            QMessageBox.warning(self, "Warning" ,"Merge Vector Layer Successfully")

    def clear_selection_item(self):
        count = self.listwidget.count()
        for i in range(count):
            item = self.listwidget.item(i)
            item.setCheckState(Qt.Unchecked)
        self.showlineedit.clear()
        self.showlineedit.setText("No Layer Selected...")

    def addFiles(self):
        file_paths,_ = QFileDialog.getOpenFileNames(self, "Open File", "", "Shapefile(*.shp);;Rasterfile(*.tif *.tiff)")

        if file_paths:
            for file_path in file_paths:
                self.selected_path = file_path
                list_item = QListWidgetItem(file_path)
                list_item.setCheckState(Qt.Unchecked)
                self.listwidget.addItem(list_item)

            #self.lineEdit_2.setText(raster_path)
            self.button_4.setEnabled(True)
        else:
            self.selected_path = None
            #self.lineEdit_2.setText("")
            self.button_4.setEnabled(False)
    
    def select_all_items(self):
        count = self.listwidget.count()
        for i in range(count):
            item = self.listwidget.item(i)
            item.setCheckState(Qt.Checked)
        self.show_selected_item(item)

    def remove_item(self):
        selected_items = [self.listwidget.item(i) for i in range (self.listwidget.count())]
        selected_text = [item.text() for item in selected_items if item.checkState() == Qt.Checked]
        for text in selected_text:
            items = self.listwidget.findItems(text, Qt.MatchExactly)
            for item in items:
                index = self.listwidget.row(item)
                self.listwidget.takeItem(index)
                self.showlineedit.clear()
                self.showlineedit.setText("No Layer Selected...")


