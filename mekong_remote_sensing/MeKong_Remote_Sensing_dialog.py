    def get_layers(self, group):
        layers = []
        for node in group.children():
            if isinstance(node, QgsLayerTreeLayer):
                layers.append(node.layer())
            elif isinstance(node, QgsLayerTreeGroup):
                layers.extend(self.get_layers(node))
        return layers
    
