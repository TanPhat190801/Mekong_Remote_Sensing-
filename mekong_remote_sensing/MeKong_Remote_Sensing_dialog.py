    def open_layer(self):
        selected_items = [self.listwidget.item(i) for i in range (self.listwidget.count())]
        selected_text = [item.text() for item in selected_items if item.checkState() == Qt.Checked]
        if len(selected_text) == 0:
            QMessageBox.warning(self, "Warning", "Vui lòng chọn ít nhất một layer...")
        else:
            for path in selected_text:
                file_info = QFileInfo(path)
                layer_name = file_info.fileName()
                if path.lower().endswith(('shp')):
                    layer = QgsVectorLayer(path, layer_name, "ogr")
                    if layer.isValid():
                        QgsProject.instance().addMapLayer(layer)
                    else:
                        QMessageBox.warning(self, "Warning", "File không hợp lệ: " + layer_name)
                elif path.lower().endswith(('.tif','.tiff')):
                    layer = QgsRasterLayer(path, layer_name)
                    if layer.isValid():
                        QgsProject.instance().addMapLayer(layer)
                    else:
                        QMessageBox.warning(self, "Warning", "File không hợp lệ: " + layer_name)
                else:
                    QMessageBox.warning(self, "Warning", "Loại layer không được hỗ trợ: " + layer_name)

    def remove_item(self):
        selected_items = [self.listwidget.item(i) for i in range (self.listwidget.count())]
        selected_text = [item.text() for item in selected_items if item.checkState() == Qt.Checked]
        for text in selected_text:
            items = self.listwidget.findItems(text, Qt.MatchExactly)
            for item in items:
                index = self.listwidget.row(item)
                self.listwidget.takeItem(index)
    
    def clear_selection_item(self):
        count = self.listwidget.count()
        for i in range(count):
            item = self.listwidget.item(i)
            item.setCheckState(Qt.Unchecked)

