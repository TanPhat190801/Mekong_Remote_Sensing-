    def testShow(self):
        selected_items = [self.listwidget.item(i) for i in range(self.listwidget.count())]
        selected_text = [item.text() for item in selected_items if item.checkState() == Qt.Checked]

        # Initialize empty lists to store information
        file_names = []
        paths = []
        crs = []
        geometry_types = []
        total_features = []
        total_fields = []
        class_values_list = []

        # Loop through selected layers and collect information
        for layer_name in selected_text:
            layer = QgsProject.instance().mapLayersByName(layer_name)[0]
            file_info = QFileInfo(layer.source())

            file_names.append(file_info.fileName())
            paths.append(layer.dataProvider().dataSourceUri())
            crs.append(layer.crs().authid())
            geometry_types.append(QgsWkbTypes.displayString(layer.wkbType()))
            total_features.append(layer.featureCount())
            total_fields.append(len(layer.fields()))
            classifica_index = layer.fields().indexFromName("Classifica")
            class_values = layer.uniqueValues(classifica_index)
            class_values_list.append(class_values if class_values else [])

        # Create the information dialog
        self.info_dialog = QDialog()
        self.info_dialog.setWindowTitle("Thông tin Layer")
        self.info_dialog.resize(1800,500)
        self.layout = QVBoxLayout()
        self.font = QtGui.QFont()
        self.font.setPointSize(14)

        # Create a table to display the information
        self.table = QTableWidget()
        self.table.setColumnCount(8)
        self.table.setHorizontalHeaderLabels(["STT", "Tên File", "Đường Dẫn", "CRS", "Kiểu Hình Học", "Tổng Số Dòng", "Tổng Số Cột", "Lớp"])
        self.table.setRowCount(len(file_names))

        # Fill the table with data
        for i in range(len(file_names)):
            row = i
            self.table.setItem(row, 0, QTableWidgetItem(str(i + 1)))
            self.table.setItem(row, 1, QTableWidgetItem(file_names[i]))
            self.table.setItem(row, 2, QTableWidgetItem(paths[i]))
            self.table.setItem(row, 3, QTableWidgetItem(crs[i]))
            self.table.setItem(row, 4, QTableWidgetItem(geometry_types[i]))
            self.table.setItem(row, 5, QTableWidgetItem(str(total_features[i])))
