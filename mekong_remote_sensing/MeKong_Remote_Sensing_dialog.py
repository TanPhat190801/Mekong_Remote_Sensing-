    def page1values(self):
        n_estimators = self.n_estimators.text()
        min_samples_split = self.min_samples_split.text()
        min_samples_leaf = self.min_samples_leaf.text()
        random_state = self.rf_random_state.text()
        if n_estimators and min_samples_split and min_samples_leaf and random_state:
            result_string = f"n_estimators: {n_estimators}\n"
            result_string += f"min_samples_split: {min_samples_split}\n"
            result_string += f"min_samples_leaf: {min_samples_leaf}\n"
            result_string += f"Random-state: {random_state}"
            return result_string
        else:
            QMessageBox.information(self, "", "Đã xảy ra lỗi, vui lòng kiểm tra lại tham số Random Forest")
    
